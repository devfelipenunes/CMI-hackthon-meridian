#!/usr/bin/env bash














set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

out="$root/artifacts/parity-vectors/allocation.json"
fixtures="$root/circuits/winner_allocation/fixtures"


cases=(poc4_8bids undersubscribed tiebreak)

note="Scenarios for winner_allocation (RF-18), transcribed from the Prover.toml files in circuits/winner_allocation/fixtures/. Generated by scripts/allocation-vectors.sh; the circuit proves exactly these values."


rhs() { grep -E "^$2 = " "$1" | head -1 | sed -E "s/^$2 = //"; }


scalar_hex() { rhs "$1" "$2" | tr -d '"'; }


scalar_dec() { printf '%d' "$(scalar_hex "$1" "$2")"; }


elements() { rhs "$1" "$2" | sed -E 's/^\[//; s/\].*$//' | tr ',' '\n' | tr -d ' "' | grep -v '^$'; }

array_dec() {
  local v out=""
  while read -r v; do
    out+="${out:+,}$(printf '%d' "$v")"
  done < <(elements "$1" "$2")
  printf '%s' "$out"
}

array_hex() {
  local v out=""
  while read -r v; do
    out+="${out:+,}\"$v\""
  done < <(elements "$1" "$2")
  printf '%s' "$out"
}

emit() {
  local name f first=1

  printf '{\n'
  printf '  "note": "%s",\n' "$note"
  printf '  "circuit": "winner_allocation",\n'
  printf '  "cases": {\n'

  for name in "${cases[@]}"; do
    f="$fixtures/$name/Prover.toml"
    if [[ ! -f "$f" ]]; then
      echo "missing $f" >&2
      exit 1
    fi

    if [[ $first -eq 1 ]]; then first=0; else printf ',\n'; fi

    printf '    "%s": {\n' "$name"
    printf '      "commitments_root": "%s",\n' "$(scalar_hex "$f" commitments_root)"
    printf '      "requested_quantities": [%s],\n' "$(array_dec "$f" requested_quantities)"
    printf '      "filled_quantities": [%s],\n' "$(array_dec "$f" filled_quantities)"
    printf '      "bid_count": %s,\n' "$(scalar_dec "$f" bid_count)"
    printf '      "total_supply": %s,\n' "$(scalar_dec "$f" total_supply)"
    printf '      "market_id": %s,\n' "$(scalar_dec "$f" market_id)"
    printf '      "auction_rule": %s,\n' "$(scalar_dec "$f" auction_rule)"
    printf '      "config_hash_lo": "%s",\n' "$(scalar_hex "$f" config_hash_lo)"
    printf '      "config_hash_hi": "%s",\n' "$(scalar_hex "$f" config_hash_hi)"
    printf '      "clearing_price": %s,\n' "$(scalar_dec "$f" clearing_price)"
    printf '      "prices": [%s],\n' "$(array_dec "$f" prices)"
    printf '      "blindings": [%s],\n' "$(array_hex "$f" blindings)"
    printf '      "nullifier_seeds": [%s],\n' "$(array_hex "$f" nullifier_seeds)"
    printf '      "participant_ids": [%s]\n' "$(array_hex "$f" participant_ids)"
    printf '    }'
  done

  printf '\n  }\n}\n'
}

tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT
emit > "$tmp"



if command -v jq >/dev/null; then
  jq -e . "$tmp" >/dev/null
fi

if [[ "${1:-}" == "--check" ]]; then



  if ! diff -u "$out" "$tmp"; then
    echo "" >&2
    echo "DIVERGE: run ./scripts/allocation-vectors.sh and version the result" >&2
    exit 1
  fi
  echo "OK: the versioned vectors are the ones these fixtures generate"
else
  cp "$tmp" "$out"
  echo "wrote $out"
fi
