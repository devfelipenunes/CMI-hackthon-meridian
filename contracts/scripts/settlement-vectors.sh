#!/usr/bin/env bash



















set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

out="$root/artifacts/parity-vectors/settlement.json"
fixtures="$root/circuits/settlement_binding/fixtures"


cases=(partial full zero)

note="Scenarios for settlement_binding (RF-20), transcribed from the Prover.toml files in circuits/settlement_binding/fixtures/. Generated by scripts/settlement-vectors.sh; the circuit proves exactly these values. The three c_* points are public inputs 4-9, in the order seller, fee, refund."


rhs() { grep -E "^$2 = " "$1" | head -1 | sed -E "s/^$2 = //"; }


scalar_hex() { rhs "$1" "$2" | tr -d '"'; }


scalar_dec() { printf '%d' "$(scalar_hex "$1" "$2")"; }

emit() {
  local name f first=1

  printf '{\n'
  printf '  "note": "%s",\n' "$note"
  printf '  "circuit": "settlement_binding",\n'
  printf '  "public_inputs": [\n'
  printf '    "bid_commitment", "requested_quantity", "filled_quantity", "fee_bps",\n'
  printf '    "c_seller", "c_fee", "c_refund"\n'
  printf '  ],\n'
  printf '  "cases": {\n'

  for name in "${cases[@]}"; do
    f="$fixtures/$name/Prover.toml"
    if [[ ! -f "$f" ]]; then
      echo "missing $f" >&2
      exit 1
    fi

    if [[ $first -eq 1 ]]; then first=0; else printf ',\n'; fi

    printf '    "%s": {\n' "$name"
    printf '      "bid_commitment": "%s",\n' "$(scalar_hex "$f" bid_commitment)"
    printf '      "requested_quantity": %s,\n' "$(scalar_dec "$f" requested_quantity)"
    printf '      "filled_quantity": %s,\n' "$(scalar_dec "$f" filled_quantity)"
    printf '      "fee_bps": %s,\n' "$(scalar_dec "$f" fee_bps)"
    printf '      "c_seller": { "x": "%s", "y": "%s" },\n' \
      "$(scalar_hex "$f" c_seller_x)" "$(scalar_hex "$f" c_seller_y)"
    printf '      "c_fee": { "x": "%s", "y": "%s" },\n' \
      "$(scalar_hex "$f" c_fee_x)" "$(scalar_hex "$f" c_fee_y)"
    printf '      "c_refund": { "x": "%s", "y": "%s" },\n' \
      "$(scalar_hex "$f" c_refund_x)" "$(scalar_hex "$f" c_refund_y)"
    printf '      "price": %s,\n' "$(scalar_dec "$f" price)"
    printf '      "market_id": %s,\n' "$(scalar_dec "$f" market_id)"
    printf '      "participant_id": %s,\n' "$(scalar_dec "$f" participant_id)"
    printf '      "fee": "%s",\n' "$(scalar_hex "$f" fee)"
    printf '      "fee_rem": "%s",\n' "$(scalar_hex "$f" fee_rem)"
    printf '      "blinding": "%s",\n' "$(scalar_hex "$f" blinding)"
    printf '      "nullifier_seed": "%s",\n' "$(scalar_hex "$f" nullifier_seed)"
    printf '      "r_seller": "%s",\n' "$(scalar_hex "$f" r_seller)"
    printf '      "r_fee": "%s",\n' "$(scalar_hex "$f" r_fee)"
    printf '      "r_refund": "%s"\n' "$(scalar_hex "$f" r_refund)"
    printf '    }'
  done

  printf '\n  }\n}\n'
}

tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT
emit > "$tmp"



if command -v jq >/dev/null; then
  jq -e . "$tmp" >/dev/null
fi

if [[ "${1:-}" == "--check" ]]; then



  if ! diff -u "$out" "$tmp"; then
    echo "" >&2
    echo "DIVERGE: run ./scripts/settlement-vectors.sh and version the result" >&2
    exit 1
  fi
  echo "OK: the versioned vectors are the ones these fixtures generate"
else
  cp "$tmp" "$out"
  echo "wrote $out"
fi
