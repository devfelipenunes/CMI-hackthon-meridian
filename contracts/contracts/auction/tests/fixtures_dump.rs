mod common;

use std::string::String;

use shared::types::QUOTA_UNIT;

fn context_path() -> String {
    std::format!(
        "{}/../../circuits/bid_validity/fixtures/{}/context.json",
        env!("CARGO_MANIFEST_DIR"),
        common::CASE
    )
}

#[test]
#[ignore = "tool: writes context.json; run with --ignored"]
fn dump_context() {
    let w = common::new_world();

    assert_eq!(
        common::participant_id(&w, &w.bidder),
        common::BIDDER_ID,
        "the bidder did not get the participant_id the fixture proves"
    );
    assert_eq!(
        common::config_hash(&w).len(),
        32,
        "open_market did not freeze the config_hash"
    );

    let hash = common::config_hash(&w);
    let (lo, hi) = auction::crypto::hash_limbs(&w.e, &hash);

    let json = std::format!(
        "{{\n  \
         \"note\": \"State values that enter the bid_validity public inputs. Generated \
         by the `dump_context` test (cargo test --test fixtures_dump -- --ignored); \
         scripts/fixtures.sh stitches it into Prover.toml.\",\n  \
         \"circuit\": \"bid_validity\",\n  \
         \"case\": \"{}\",\n  \
         \"market_id\": {},\n  \
         \"participant_id\": {},\n  \
         \"requested_quantity\": {},\n  \
         \"min_price_per_quota\": {},\n  \
         \"config_hash\": \"{}\",\n  \
         \"config_hash_lo\": \"{}\",\n  \
         \"config_hash_hi\": \"{}\",\n  \
         \"addresses\": {{\n    \
         \"auction\": \"{}\",\n    \
         \"seller\": \"{}\",\n    \
         \"bidder\": \"{}\",\n    \
         \"collateral_token\": \"{}\"\n  \
         }}\n\
         }}\n",
        common::CASE,
        common::MARKET_ID,
        common::participant_id(&w, &w.bidder),
        common::REQUESTED_QUANTITY,
        common::MIN_PRICE_PER_QUOTA,
        common::hex(&hash.to_array()),
        common::hex_bytes(&lo),
        common::hex_bytes(&hi),
        w.auction.to_string(),
        w.seller.to_string(),
        w.bidder.to_string(),
        w.collateral_token.to_string(),
    );

    let path = context_path();
    std::fs::write(&path, &json).expect("write context.json");

    let written = std::fs::read_to_string(&path).expect("read context.json back");
    assert!(
        written.contains(&common::hex(&hash.to_array())),
        "the context.json does not carry the world's config_hash"
    );

    std::println!("context.json written to {path}");
    std::println!("config_hash: {}", common::hex(&hash.to_array()));
    std::println!(
        "open_market escrow: {} base units",
        common::TOTAL_QUOTAS as i128 * QUOTA_UNIT
    );
}

